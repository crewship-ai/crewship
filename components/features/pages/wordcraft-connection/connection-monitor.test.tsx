import { act, fireEvent, render, screen } from "@testing-library/react"
import { afterEach, beforeEach, describe, expect, it, vi } from "vitest"
import { WordCraftConnectionIndicator, wordCraftConnectionLabel } from "./connection-indicator"
import { WordCraftConnectionMonitor } from "./connection-monitor"

beforeEach(() => { vi.useFakeTimers() })
afterEach(() => { vi.useRealTimers() })

const saved = (monitor: WordCraftConnectionMonitor, connection: number, revision = "1", confirmedDraftVersion?: number) => monitor.observeServer(connection, { kind: "receipt", revision, saveState: "saved", confirmedDraftVersion })

describe("WordCraft connection status", () => {
  it("expires a saved state after the configured silence limit even without edits", () => {
    const monitor = new WordCraftConnectionMonitor(1_000)
    const connection = monitor.beginConnection()
    saved(monitor, connection)
    render(<WordCraftConnectionIndicator monitor={monitor} />)
    expect(screen.getByRole("status")).toHaveTextContent(/^Uloženo$/)
    act(() => vi.advanceTimersByTime(999))
    expect(screen.getByRole("status")).toHaveTextContent(/^Uloženo$/)
    act(() => vi.advanceTimersByTime(1))
    expect(screen.getByRole("status")).toHaveTextContent("nespojeno · stav uložení nepotvrzen")
    expect(screen.getByRole("status")).not.toHaveTextContent("Uloženo")
    monitor.dispose()
  })

  it("shows a retained draft and never restores Saved from a heartbeat", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    saved(monitor, connection)
    const draft = monitor.retainDraft()
    vi.advanceTimersByTime(100)
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).toContain("nespojeno · neuloženo")
    monitor.observeServer(connection, { kind: "heartbeat" })
    expect(monitor.getSnapshot().phase).toBe("connecting")
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).not.toBe("Uloženo")
    // Current server state does not prove that an unknown local operation saved.
    monitor.observeServer(connection, { kind: "snapshot", revision: "1", saveState: "saved" })
    expect(monitor.getSnapshot().hasUnconfirmedDraft).toBe(true)
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).not.toBe("Uloženo")
    saved(monitor, connection, "2", draft)
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).toBe("Uloženo")
    monitor.dispose()
  })

  it("does not let a receipt for earlier input clear text typed afterwards", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    const first = monitor.retainDraft()
    const second = monitor.retainDraft()
    saved(monitor, connection, "1", first)
    expect(monitor.getSnapshot().hasUnconfirmedDraft).toBe(true)
    saved(monitor, connection, "2", second)
    expect(monitor.getSnapshot().hasUnconfirmedDraft).toBe(false)
    monitor.dispose()
  })

  it("ignores stale revisions, duplicate receipts and callbacks from the old transport", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const old = monitor.beginConnection()
    saved(monitor, old, "10")
    const draft = monitor.retainDraft()
    const current = monitor.beginConnection()
    expect(saved(monitor, old, "11", draft)).toBe(false)
    monitor.disconnected(old)
    expect(monitor.getSnapshot().phase).toBe("connecting")
    expect(saved(monitor, current, "9", draft)).toBe(false)
    expect(saved(monitor, current, "10", draft)).toBe(false)
    expect(monitor.getSnapshot().hasUnconfirmedDraft).toBe(true)
    expect(monitor.observeServer(current, { kind: "snapshot", revision: "10", saveState: "saved" })).toBe(true)
    expect(monitor.getSnapshot().hasUnconfirmedDraft).toBe(true)
    expect(saved(monitor, current, "11", draft)).toBe(true)
    expect(saved(monitor, current, "11", draft)).toBe(false)
    expect(monitor.getSnapshot()).toMatchObject({ phase: "connected", revision: "11", hasUnconfirmedDraft: false })
    monitor.dispose()
  })

  it.each(["saving", "unknown"] as const)("accepts %s to durable Saved for the same revision without clearing later input", saveState => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    const first = monitor.retainDraft()
    monitor.observeServer(connection, { kind: "snapshot", revision: "1", saveState })
    const later = monitor.retainDraft()
    expect(saved(monitor, connection, "1", first)).toBe(true)
    expect(monitor.getSnapshot()).toMatchObject({ serverSaveState: "saved", hasUnconfirmedDraft: true })
    expect(saved(monitor, connection, "1", later)).toBe(false)
    expect(monitor.observeServer(connection, { kind: "receipt", revision: "1", saveState: "saving" })).toBe(false)
    expect(monitor.getSnapshot()).toMatchObject({ serverSaveState: "saved", hasUnconfirmedDraft: true })
    expect(saved(monitor, connection, "2", later)).toBe(true)
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).toBe("Uloženo")
    monitor.dispose()
  })

  it("counts duplicate server traffic as liveness without accepting its state", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    saved(monitor, connection)
    const draft = monitor.retainDraft()
    vi.advanceTimersByTime(90)
    expect(saved(monitor, connection, "1", draft)).toBe(false)
    vi.advanceTimersByTime(90)
    expect(monitor.getSnapshot()).toMatchObject({ phase: "connected", hasUnconfirmedDraft: true })
    vi.advanceTimersByTime(10)
    expect(monitor.getSnapshot().phase).toBe("disconnected")
    monitor.dispose()
  })

  it("rejects malformed or impossible confirmations without extending the deadline", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    saved(monitor, connection)
    vi.advanceTimersByTime(90)
    expect(saved(monitor, connection, "02")).toBe(false)
    expect(saved(monitor, connection, "18446744073709551616")).toBe(false)
    expect(saved(monitor, connection, "2", 1)).toBe(false)
    expect(saved(monitor, connection, "2", -1)).toBe(false)
    expect(saved(monitor, connection, "2", 0.5)).toBe(false)
    vi.advanceTimersByTime(10)
    expect(monitor.getSnapshot().phase).toBe("disconnected")
    monitor.dispose()
  })

  it("accepts bigint revision ordering without rounding and renders saving or unknown state", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    monitor.observeServer(connection, { kind: "snapshot", revision: "9007199254740992", saveState: "saving" })
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).toBe("Ukládání…")
    saved(monitor, connection, "9007199254740993")
    expect(monitor.getSnapshot().revision).toBe("9007199254740993")
    monitor.observeServer(connection, { kind: "receipt", revision: "9007199254740994", saveState: "unknown" })
    expect(wordCraftConnectionLabel(monitor.getSnapshot())).toBe("stav uložení nepotvrzen")
    monitor.dispose()
  })

  it.each([0, -1, NaN, Infinity, 2_147_483_648])("requires an explicit valid silence limit: %s", limit => {
    expect(() => new WordCraftConnectionMonitor(limit)).toThrow("invalid_server_silence_limit")
  })

  it("stops notifying and refuses old work after disposal", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    const connection = monitor.beginConnection()
    const listener = vi.fn()
    const unsubscribe = monitor.subscribe(listener)
    saved(monitor, connection)
    expect(listener).toHaveBeenCalledTimes(1)
    unsubscribe()
    monitor.retainDraft()
    expect(listener).toHaveBeenCalledTimes(1)
    monitor.dispose()
    expect(saved(monitor, connection, "2")).toBe(false)
    expect(() => monitor.retainDraft()).toThrow("disposed")
    expect(() => monitor.beginConnection()).toThrow("disposed")
    vi.advanceTimersByTime(100)
    expect(listener).toHaveBeenCalledTimes(1)
  })

  it("simulates stopped incoming messages while preserving the same mounted editor and IME draft", () => {
    const monitor = new WordCraftConnectionMonitor(100)
    let connection = monitor.beginConnection()
    saved(monitor, connection)
    render(<><WordCraftConnectionIndicator monitor={monitor} /><div data-testid="draft" contentEditable suppressContentEditableWarning onInput={() => monitor.retainDraft()} /></>)
    const editor = screen.getByTestId("draft")
    editor.textContent = "Žluťoučký kůň "
    fireEvent.compositionStart(editor)
    fireEvent.input(editor, { data: "rozepsáno", isComposing: true })
    editor.textContent += "rozepsáno"
    const pump = setInterval(() => { monitor.observeServer(connection, { kind: "heartbeat" }) }, 25)
    act(() => vi.advanceTimersByTime(150))
    expect(screen.getByRole("status")).not.toHaveTextContent("nespojeno")
    clearInterval(pump) // The receive loop stops; no close event is delivered.
    act(() => vi.advanceTimersByTime(100))
    expect(screen.getByRole("status")).toHaveTextContent("nespojeno")
    expect(screen.getByTestId("draft")).toBe(editor)
    expect(editor.textContent).toBe("Žluťoučký kůň rozepsáno")
    act(() => { connection = monitor.beginConnection() })
    act(() => { monitor.observeServer(connection, { kind: "heartbeat" }) })
    expect(screen.getByRole("status")).not.toHaveTextContent("Uloženo")
    act(() => { monitor.observeServer(connection, { kind: "snapshot", revision: "1", saveState: "saved" }) })
    expect(screen.getByRole("status")).toHaveTextContent("neuloženo")
    expect(editor.textContent).toBe("Žluťoučký kůň rozepsáno")
    fireEvent.compositionEnd(editor)
    monitor.dispose()
  })
})
