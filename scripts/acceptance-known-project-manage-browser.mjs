// Called only by the existing owned Router/migrated-DB/static-export harness.
// Uses real production routes and synthetic sessions; no request mocks/runtime.
import { expect } from '@playwright/test'
import { join } from 'node:path'
export async function knownProjectManage({fixture, contexts, pages, check, open, output}) {
  const base = `${fixture.server}/api/v1/workspaces/${fixture.workspace}`
  async function project(name) {
    const response = await contexts.owner.request.post(`${fixture.server}/api/v1/projects?workspace_id=${fixture.workspace}`, {data:{name}})
    if(response.status()!==201)throw new Error('known project fixture create')
    return response.json()
  }
  const a = await project('Known client A project'), b = await project('Known client B private project')
  async function rights(user, projectId, operations) {
    const path = `${base}/members/${fixture.members[user]}/access`
    const snapshot = await (await contexts.owner.request.get(path)).json()
    const response = await contexts.owner.request.put(path, {data:{membership_id:snapshot.membership_id,revision:snapshot.revision,mode:'restricted',rights:operations.map(operation=>({kind:'project',id:projectId,operation}))}})
    if(response.status()!==200)throw new Error('known project grant setup')
    const current = await (await contexts.owner.request.get(path)).json()
    await check(`${user} custom rights remain explicit without List or Contribute`, current.rights.length===operations.length && current.rights.every(right=>operations.includes(right.operation)))
  }
  await rights('nav-client-a',a.id,['read','manage'])
  await rights('nav-client-b',b.id,['read','manage'])
  const requests = []
  for(const actor of ['desktop','phone','other'])pages[actor].on('request',request=>{
    const path = new URL(request.url()).pathname
    if(path.startsWith('/api/'))requests.push({actor,method:request.method(),path})
  })
  const link = id => `/issues/manage?project=${encodeURIComponent(id)}`
  for(const actor of ['desktop','phone']) {
    await open(actor,link(a.id))
    await expect(pages[actor].getByLabel('Project name',{exact:true})).toHaveValue(a.name)
    await expect(pages[actor].getByRole('link',{name:'Issues',exact:true})).toHaveCount(0)
    await expect(pages[actor].getByLabel('Shared project',{exact:true})).toHaveCount(0)
    await pages[actor].getByLabel('Project description',{exact:true}).fill(`${actor} known-ID project edit`)
    const written = pages[actor].waitForResponse(response=>new URL(response.url()).pathname===`/api/v1/workspaces/${fixture.workspace}/restricted-projects/${a.id}` && response.request().method()==='PUT')
    await pages[actor].getByRole('button',{name:'Save project details',exact:true}).click()
    await check(`${actor} Read+Manage edits known metadata without List`,(await written).status()===200)
    await expect(pages[actor].getByRole('button',{name:'Save project details',exact:true})).toBeEnabled()
    await pages[actor].screenshot({path:join(output,`${actor}-known-project.png`)})
  }
  await open('other',link(b.id))
  await expect(pages.other.getByLabel('Project name',{exact:true})).toHaveValue(b.name)
  // Read+Manage does not disclose the other client's known project.
  await open('desktop',link(b.id))
  await expect(pages.desktop.getByRole('region',{name:'Shared project details',exact:true}).getByRole('alert')).toHaveText(/unavailable/)
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toHaveCount(0)
  await check('foreign known ID stays absent without catalog fallback',!(await pages.desktop.locator('body').innerText()).includes(b.name))
  await open('desktop',link(a.id))
  const details = pages.desktop.getByRole('region',{name:'Shared project details',exact:true})
  const description = details.getByLabel('Project description',{exact:true})
  await expect(description).toBeVisible()
  await description.fill('Known-ID retained conflict draft')
  const staff = await contexts.owner.request.patch(`${fixture.server}/api/v1/projects/${a.id}?workspace_id=${fixture.workspace}`,{data:{description:'Known-ID staff revision'}})
  if(staff.status()!==200)throw new Error('known project staff edit')
  const conflict = pages.desktop.waitForResponse(response=>response.request().method()==='PUT' && response.url().includes(`/restricted-projects/${a.id}`))
  await details.getByRole('button',{name:'Save project details',exact:true}).click()
  await check('known-ID metadata still uses reviewed CAS',(await conflict).status()===409)
  await expect(description).toHaveValue('Known-ID retained conflict draft')
  await expect(details.getByRole('button',{name:'Load current details',exact:true})).toBeEnabled()
  await details.getByRole('button',{name:'Load current details',exact:true}).click()
  await expect(description).toHaveValue('Known-ID staff revision')
  const milestones = pages.desktop.getByRole('region',{name:'Shared project milestones',exact:true})
  const create = milestones.getByLabel('New milestone',{exact:true})
  await create.getByText('New milestone',{exact:true}).click()
  await create.getByLabel('Milestone name',{exact:true}).fill('Known-ID milestone')
  const created = pages.desktop.waitForResponse(response=>response.request().method()==='POST' && new URL(response.url()).pathname.endsWith('/milestones'))
  await create.getByRole('button',{name:'Create milestone',exact:true}).click()
  await check('known-ID creates milestone without issue discovery',(await created).status()===201)
  const card = milestones.getByRole('article',{name:'Milestone Known-ID milestone',exact:true})
  await expect(card).toBeVisible()
  await card.getByText('Edit milestone',{exact:true}).click()
  await card.getByLabel('Milestone description',{exact:true}).fill('Known-ID edited milestone')
  const edited = pages.desktop.waitForResponse(response=>response.request().method()==='PUT' && /\/milestones\/[^/]+$/.test(new URL(response.url()).pathname))
  await card.getByRole('button',{name:'Save milestone',exact:true}).click()
  await check('known-ID updates milestone with reviewed version',(await edited).status()===200)
  await expect(card.getByRole('button',{name:'Save milestone',exact:true})).toBeEnabled()
  await expect(card.locator('p').filter({hasText:'Known-ID edited milestone'})).toBeVisible()
  await card.getByRole('button',{name:'Remove milestone',exact:true}).click()
  const removed = pages.desktop.waitForResponse(response=>response.request().method()==='DELETE' && /\/milestones\/[^/]+$/.test(new URL(response.url()).pathname))
  await pages.desktop.getByRole('button',{name:'Remove empty milestone',exact:true}).click()
  await check('known-ID deletes only reviewed empty milestone',(await removed).status()===204)
  await expect(card).toHaveCount(0)
  // The exact boundary is not an Issues navigation or query bypass.
  for(const route of ['/issues','/chat','/credentials']) {
    await open('desktop',route)
    await expect(pages.desktop.getByText(/isn’t part of your access$/)).toBeVisible()
  }
  await open('desktop',`${link(a.id)}&search=private`)
  await expect(pages.desktop.getByRole('alert').filter({hasText:/known project/})).toHaveText(/known project/)
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toHaveCount(0)
  await open('desktop',link(a.id))
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toBeVisible()
  await rights('nav-client-a',a.id,['read'])
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toHaveCount(0,{timeout:25000})
  await expect(pages.desktop.getByRole('region',{name:'Shared project milestones',exact:true})).toHaveCount(0)
  await pages.other.getByRole('button',{name:'Refresh project details',exact:true}).click()
  await expect(pages.other.getByLabel('Project name',{exact:true})).toHaveValue(b.name)
  await check('revocation clears A while independent client B keeps its project',true)
  await rights('nav-client-a',a.id,['manage'])
  await open('desktop',link(a.id))
  await expect(pages.desktop.getByRole('region',{name:'Shared project details',exact:true}).getByRole('alert')).toHaveText(/unavailable/)
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toHaveCount(0)
  await check('Manage-only known project still requires Read',true)
  const issueResponse = await contexts.owner.request.post(`${fixture.server}/api/v1/crews/crew_test_${fixture.workspace}/issues?workspace_id=${fixture.workspace}`,{data:{title:'Disposable known-ID request',project_id:a.id,status:'BACKLOG'}})
  if(issueResponse.status()!==201)throw new Error('known issue fixture create')
  const issue = await issueResponse.json()
  const issueLink = `${link(a.id)}&issue_id=${encodeURIComponent(issue.id)}`
  await rights('nav-client-a',a.id,['read','manage'])
  await open('desktop',issueLink)
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toBeVisible()
  await expect(pages.desktop.getByRole('button',{name:'Delete issue',exact:true})).toHaveCount(0)
  await check('known issue ID does not imply delete_issues',true)
  await rights('nav-client-a',a.id,['read','manage','delete_issues'])
  await open('desktop',issueLink)
  await pages.desktop.getByRole('button',{name:'Delete issue',exact:true}).click()
  await expect(pages.desktop.getByRole('alertdialog',{name:`Delete ${issue.identifier}?`})).toBeVisible()
  const staffIssuePath = `${fixture.server}/api/v1/crews/crew_test_${fixture.workspace}/issues/${issue.identifier}?workspace_id=${fixture.workspace}`
  if((await contexts.owner.request.patch(staffIssuePath,{data:{title:'Changed known-ID deletion snapshot'}})).status()!==200)throw new Error('known issue concurrent edit')
  const staleDelete = pages.desktop.waitForResponse(response=>response.request().method()==='DELETE' && new URL(response.url()).pathname.endsWith(`/restricted-issues/${issue.id}`))
  await pages.desktop.getByRole('button',{name:'Permanently delete issue',exact:true}).click()
  await check('known issue deletion refuses a stale reviewed snapshot',(await staleDelete).status()===409)
  await expect(pages.desktop.getByRole('button',{name:'Permanently delete issue',exact:true})).toBeDisabled()
  await pages.desktop.getByRole('button',{name:'Keep issue',exact:true}).click()
  await pages.desktop.getByRole('button',{name:'Delete issue',exact:true}).click()
  const deletion = pages.desktop.waitForResponse(response=>response.request().method()==='DELETE' && new URL(response.url()).pathname.endsWith(`/restricted-issues/${issue.id}`))
  await pages.desktop.getByRole('button',{name:'Permanently delete issue',exact:true}).click()
  await check('known-ID deletion confirms current audience and version',(await deletion).status()===204)
  await expect(pages.desktop.getByText('Known issue deleted.',{exact:true})).toBeVisible()
  await expect(pages.desktop).toHaveURL(new RegExp(`/issues/manage\\?project=${a.id}&issue_id=${issue.id}$`))
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toBeVisible()
  const forbidden = requests.filter(({path})=>!(path==='/api/auth/session' || path==='/api/auth/csrf' || path==='/api/v1/workspaces' || new RegExp(`^/api/v1/workspaces/${fixture.workspace}/restricted-projects/[^/]+(?:/milestones(?:/[^/]+)?)?$`).test(path) || new RegExp(`^/api/v1/workspaces/${fixture.workspace}/restricted-issues/${issue.id}(?:/deletion)?$`).test(path)))
  await check('known-ID flow sends no catalog, issue collection, count, trusted or execution request',forbidden.length===0,{forbidden})
  await rights('nav-client-a',a.id,['read','manage'])
  await pages.desktop.getByRole('button',{name:'Refresh project details',exact:true}).click()
  await expect(pages.desktop.getByLabel('Project name',{exact:true})).toHaveValue(a.name)
  await check('restored known-ID access starts with current server values',true)
}
