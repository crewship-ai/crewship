// Run only under scripts/throwaway-server.sh run NAME --documents --binary PATH.
// Docs Canvas at content schema 6, end to end in a real browser against the
// production Node engine and Go authority: an editor places and moves a block,
// the placement survives a reload, and a second person with read-only access
// can pan the canvas but not move anything. Two real identities, no model or
// provider. DOCS_CANVAS_OUT names where screenshots and videos go.
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import { readFile, mkdir, mkdtemp, open, stat } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { chromium } from 'playwright'
import * as Y from 'yjs'

const base = process.env.CREWSHIP_SERVER
const manifestPath = process.env.CREWSHIP_THROWAWAY_MANIFEST
if (!base || !manifestPath) throw new Error('Use the supported throwaway run command with --documents.')
assert.equal(new URL(base).hostname, '127.0.0.1', 'fixture targets its local disposable server')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
assert.equal(manifest.state, 'running')
const ownRoot = resolve(dirname(manifestPath))
const { documents_service_socket: socket, documents_authority_socket: authority, documents_service_token_file: token } = manifest
for (const path of [socket, authority, token]) {
  assert.equal(typeof path, 'string', 'Docs path must be generated by --documents')
  assert.ok(resolve(path).startsWith(ownRoot + '/'), 'Docs path belongs to this instance')
}
assert.equal((await stat(token)).mode & 0o777, 0o600)
const output = process.env.DOCS_CANVAS_OUT || await mkdtemp(join(tmpdir(), 'crewship-docs-canvas-'))
await mkdir(join(output, 'video'), { recursive: true })
const engineLog = await open(join(output, 'engine.log'), 'w', 0o600)
const engine = spawn(process.execPath, [resolve('tools/docs-service/service.mjs')], {
  env: { CREWSHIP_DOCS_SOCKET: socket, CREWSHIP_DOCS_AUTHORITY_SOCKET: authority, CREWSHIP_DOCS_SERVICE_TOKEN_FILE: token },
  stdio: ['ignore', engineLog.fd, engineLog.fd],
})
const report = { output, checks: [] }
const pass = name => { report.checks.push(name); console.log('PASS', name) }
const decode = value => Uint8Array.from(Buffer.from(value, 'base64'))
const world = page => page.locator('[data-canvas-world]').evaluate(element => element.style.transform)

let browser
try {
  browser = await chromium.launch({ headless: true })
  const viewport = { width: 1440, height: 1000 }
  const video = { dir: join(output, 'video'), size: viewport }
  const owner = await browser.newContext({ viewport, reducedMotion: 'reduce', recordVideo: video })
  const bootstrap = await owner.request.post(`${base}/api/v1/bootstrap`, { data: { full_name: 'Canvas Editor', email: 'canvas-editor@example.invalid', password: 'disposable-canvas-editor-password' } })
  assert.equal(bootstrap.status(), 201, 'fresh disposable bootstrap')
  const { workspace_id: workspace } = await bootstrap.json()
  const q = `workspace_id=${encodeURIComponent(workspace)}`
  assert.equal((await owner.request.post(`${base}/api/v1/onboarding/complete`, { data: { skipped: true } })).status(), 200)
  let enabled = false
  for (let attempt = 0; attempt < 100 && !enabled; attempt++) {
    if (engine.exitCode !== null || engine.signalCode !== null) throw new Error('Owned Node engine exited; inspect engine.log')
    const status = await owner.request.get(`${base}/api/v1/documents/status?${q}`)
    enabled = status.ok() && (await status.json()).enabled === true
    if (!enabled) await new Promise(r => setTimeout(r, 100))
  }
  assert.ok(enabled, 'real Node service becomes available')

  // A schema 6 document, initialized explicitly (nothing upgrades implicitly).
  const created = await owner.request.post(`${base}/api/v1/pages?${q}`, { data: { name: 'Canvas plan', slug: 'canvas-plan', panels: [], allow_empty: true } })
  assert.equal(created.status(), 201, await created.text())
  const pageId = (await created.json()).id
  const p = (id, text) => ({ type: 'paragraph', attrs: { id }, content: [{ type: 'text', text }] })
  const body = { type: 'doc', content: [{ type: 'heading', attrs: { id: 'title', level: 1 }, content: [{ type: 'text', text: 'Launch plan' }] }, p('intro', 'Agree the launch date with sales.'), p('outro', 'Book the venue.')] }
  const init = await owner.request.post(`${base}/api/v1/pages/canvas-plan/document/initialize?${q}`, { data: { id: crypto.randomUUID(), schema: 6, page_id: pageId, body } })
  assert.equal(init.status(), 200, await init.text())
  pass('schema 6 document initialized through the public API')

  // The second identity: a workspace Viewer with its own password.
  const provisioned = await owner.request.post(`${base}/api/v1/workspaces/${encodeURIComponent(workspace)}/members/provision?${q}`, { data: { email: 'canvas-viewer@example.invalid', role: 'VIEWER', full_name: 'Canvas Viewer', create_only: true } })
  assert.ok(provisioned.status() < 300, await provisioned.text())
  const setup = new URL((await provisioned.json()).setup_url).searchParams.get('token')
  // The Page is shared read-only with the workspace (a page is a per-object ACL).
  const grant = await owner.request.put(`${base}/api/v1/pages/canvas-plan/grants?${q}`, { data: { subject_type: 'workspace', level: 'read' } })
  assert.ok(grant.status() < 300, await grant.text())
  const viewerPassword = 'disposable-canvas-viewer-password'
  assert.ok((await owner.request.post(`${base}/api/v1/auth/reset`, { data: { token: setup, new_password: viewerPassword } })).status() < 300)

  const errors = []
  const page = await owner.newPage()
  page.on('pageerror', error => errors.push(error.message))
  await page.goto(`${base}/artifacts/${encodeURIComponent(pageId)}`)
  const editor = page.getByLabel('Document editor', { exact: true })
  await editor.waitFor()
  await page.getByRole('tab', { name: 'Canvas', exact: true }).click()
  const canvas = page.getByRole('application', { name: 'Canvas' })
  await canvas.waitFor()
  assert.equal(await page.locator('[data-docs-canvas]').getAttribute('data-editable'), 'true')
  await page.screenshot({ path: join(output, '01-editor-empty-canvas.png') })
  // Only a patch that carries the placement counts (the editor may save its own normalization first).
  const placementPatch = r => r.url().includes('/document/patch') && r.request().method() === 'POST' && Buffer.from(JSON.parse(r.request().postData() || '{}').update || '', 'base64').includes('surface:placements')
  let saved = page.waitForResponse(placementPatch)
  await page.getByText(/^Add blocks \(3\)$/).click()
  await page.getByRole('button', { name: 'Agree the launch date with sales.', exact: true }).click()
  assert.equal((await saved).status(), 200, 'placing a block saves a patch')
  const card = page.locator('[data-placement="intro"]')
  await card.waitFor()
  pass('editor placed a Page block on the canvas')
  // Move the card by dragging it: geometry only, one write for the gesture.
  const before = await card.boundingBox()
  // A move overwrites the key, so its update names no root; the stored read-back below proves it.
  saved = page.waitForResponse(r => r.url().includes('/document/patch') && r.request().method() === 'POST')
  await page.mouse.move(before.x + 40, before.y + 20)
  await page.mouse.down()
  for (let i = 1; i <= 10; i++) await page.mouse.move(before.x + 40 + i * 24, before.y + 20 + i * 12)
  await page.mouse.up()
  assert.equal((await saved).status(), 200, 'the move saves a patch')
  await page.getByRole('button', { name: 'Status: Saved' }).waitFor({ timeout: 15000 })
  await page.screenshot({ path: join(output, '02-editor-moved.png') })

  const read = async () => {
    const response = await owner.request.get(`${base}/api/v1/pages/canvas-plan/document?${q}`)
    assert.equal(response.status(), 200)
    const value = await response.json()
    assert.equal(value.schema, 6)
    const doc = new Y.Doc({ gc: false })
    Y.applyUpdate(doc, decode(value.snapshot)); for (const update of value.updates ?? []) Y.applyUpdate(doc, decode(update))
    const placement = doc.getMap('surface:placements').get('intro')
    const text = doc.getXmlFragment('default').toString()
    doc.destroy()
    return { placement, text, content: JSON.stringify(value.content) }
  }
  const stored = await read()
  assert.ok(stored.placement, 'the server stores the placement')
  assert.ok(stored.placement.x > 0 && stored.placement.y > 0, `the move is stored: ${JSON.stringify(stored.placement)}`)
  assert.match(stored.content, /Agree the launch date with sales\./, 'the Page text is unchanged by the canvas')
  pass('server read returns the moved placement and the unchanged Page')

  await page.reload()
  await page.getByLabel('Document editor', { exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Canvas', exact: true }).click()
  await page.locator('[data-placement="intro"]').waitFor()
  const style = await page.locator('[data-placement="intro"]').evaluate(element => ({ left: element.style.left, top: element.style.top }))
  assert.deepEqual(style, { left: `${stored.placement.x}px`, top: `${stored.placement.y}px` }, 'after reload the card is where it was saved')
  await page.screenshot({ path: join(output, '03-editor-after-reload.png') })
  pass('save then reload keeps the placement')

  // Zoom and fit in the browser: the zoom readout follows, the card stays where it was saved.
  await page.getByRole('button', { name: 'Zoom in' }).click()
  assert.equal(await page.locator('[data-zoom]').innerText(), '120%')
  await page.getByRole('button', { name: 'Fit to screen' }).click()
  assert.notEqual(await page.locator('[data-zoom]').innerText(), '120%')
  pass('zoom and fit change only the view')

  // C05: a thread on the Page block shows on its card and opens the same thread.
  const head = await (await owner.request.get(`${base}/api/v1/pages/canvas-plan/document?${q}`)).json()
  const thread = await owner.request.post(`${base}/api/v1/pages/canvas-plan/document/comments?${q}`, { data: { id: crypto.randomUUID(), schema: head.schema, page_id: pageId, epoch: head.epoch, ifRev: head.rev, block: 'intro', from: 0, to: 5, text: 'Is the date confirmed?' } })
  assert.ok(thread.status() < 300, await thread.text())
  await page.reload()
  await page.getByLabel('Document editor', { exact: true }).waitFor()
  await page.getByRole('tab', { name: 'Canvas', exact: true }).click()
  const badge = page.locator('[data-card-comments="intro"]')
  await badge.waitFor({ timeout: 15000 })
  assert.equal(await badge.getAttribute('aria-label'), '1 open comment on this block')
  await badge.click()
  await page.getByRole('complementary', { name: 'Comments' }).getByText('Is the date confirmed?').waitFor()
  await page.screenshot({ path: join(output, '03b-editor-card-comment.png') })
  assert.equal((await read()).placement.x, stored.placement.x, 'commenting does not move the card')
  pass('a block comment shows on its card and opens the same thread')

  // Read-only: a Viewer in their own browser context.
  const viewerContext = await browser.newContext({ viewport, reducedMotion: 'reduce', recordVideo: video })
  const csrf = (await (await viewerContext.request.get(`${base}/api/auth/csrf`)).json()).csrfToken
  const login = await viewerContext.request.post(`${base}/api/auth/callback/credentials`, { data: { email: 'canvas-viewer@example.invalid', password: viewerPassword, csrfToken: csrf, redirect: 'false', json: 'true' } })
  assert.equal(login.status(), 200, 'viewer password login')
  const session = await (await viewerContext.request.get(`${base}/api/auth/session`)).json()
  assert.equal(session.user?.email, 'canvas-viewer@example.invalid', 'a second, distinct identity')
  const viewer = await viewerContext.newPage()
  viewer.on('pageerror', error => errors.push(error.message))
  const writes = []
  viewer.on('request', r => { if (r.method() === 'POST' && r.url().includes('/document/patch')) writes.push(r.url()) })
  const viewerRead = await viewerContext.request.get(`${base}/api/v1/pages/canvas-plan/document?${q}`)
  console.log('viewer document read', viewerRead.status(), viewerRead.ok() ? JSON.stringify({ can_write: (await viewerRead.json()).can_write }) : (await viewerRead.text()).slice(0, 200))
  await viewer.goto(`${base}/artifacts/${encodeURIComponent(pageId)}`)
  try { await viewer.getByLabel('Document editor', { exact: true }).waitFor() } catch (error) { await viewer.screenshot({ path: join(output, 'viewer-failure.png') }); throw error }
  await viewer.getByRole('button', { name: 'Status: Read-only' }).waitFor({ timeout: 15000 })
  await viewer.getByRole('tab', { name: 'Canvas', exact: true }).click()
  await viewer.getByRole('application', { name: 'Canvas' }).waitFor()
  assert.equal(await viewer.locator('[data-docs-canvas]').getAttribute('data-editable'), 'false')
  assert.equal(await viewer.getByText(/^Add blocks/).count(), 0, 'no Add blocks for a viewer')
  assert.equal(await viewer.getByRole('button', { name: 'Add note' }).count(), 0, 'no Add note for a viewer')
  const viewerCard = viewer.locator('[data-placement="intro"]')
  await viewerCard.waitFor()
  const cardBefore = await viewerCard.evaluate(element => ({ left: element.style.left, top: element.style.top }))
  const panBefore = await world(viewer)
  // Drag the empty background: the view pans.
  await viewer.mouse.move(1200, 800); await viewer.mouse.down()
  for (let i = 1; i <= 10; i++) await viewer.mouse.move(1200 - i * 30, 800 - i * 15)
  await viewer.mouse.up()
  const panAfter = await world(viewer)
  assert.notEqual(panAfter, panBefore, 'the viewer can pan')
  // Drag the card itself: it pans too, the card stays where it is and nothing is written.
  const box = await viewerCard.boundingBox()
  await viewer.mouse.move(box.x + 30, box.y + 15); await viewer.mouse.down()
  for (let i = 1; i <= 10; i++) await viewer.mouse.move(box.x + 30 + i * 20, box.y + 15 + i * 10)
  await viewer.mouse.up()
  assert.deepEqual(await viewerCard.evaluate(element => ({ left: element.style.left, top: element.style.top })), cardBefore, 'the viewer cannot move a card')
  assert.notEqual(await world(viewer), panAfter, 'dragging a card pans the view instead')
  await viewer.keyboard.press('Tab')
  await viewer.waitForTimeout(1500)
  assert.deepEqual(writes, [], 'the viewer sends no document writes')
  assert.deepEqual((await read()).placement, stored.placement, 'the stored placement is unchanged by the viewer')
  await viewer.screenshot({ path: join(output, '04-viewer-panned.png') })
  pass('read-only viewer pans but cannot move; nothing is written')

  assert.deepEqual(errors, [], 'no browser runtime errors')
  const videos = [await page.video()?.path(), await viewer.video()?.path()]
  await owner.close(); await viewerContext.close()
  report.videos = videos
  console.log(JSON.stringify({ ...report, schema: 6, identities: 2, engine: 'production Node', persistence: 'Go authority/SQLite', providerInvoked: false }))
} finally {
  try { await browser?.close() } finally {
    try {
      if (engine.exitCode === null && engine.signalCode === null) {
        const exited = once(engine, 'exit')
        engine.kill('SIGTERM')
        let timer
        const finished = await Promise.race([exited.then(() => true), new Promise(r => { timer = setTimeout(() => r(false), 5000) })])
        clearTimeout(timer)
        if (!finished) { engine.kill('SIGKILL'); await exited }
      }
    } finally { await engineLog.close() }
  }
}
