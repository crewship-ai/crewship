// Run only under scripts/throwaway-server.sh run NAME --documents --binary PATH.
// This is a human browser/Node/Go/SQLite flow; it invokes no model or provider.
import assert from 'node:assert/strict'
import { spawn } from 'node:child_process'
import { once } from 'node:events'
import { readFile, mkdtemp, open, stat } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join, resolve } from 'node:path'
import { chromium } from 'playwright'

const base = process.env.CREWSHIP_SERVER
const manifestPath = process.env.CREWSHIP_THROWAWAY_MANIFEST
if (!base || !manifestPath) throw new Error('Use the supported throwaway run command with --documents.')
const target = new URL(base)
assert.equal(target.hostname, '127.0.0.1', 'fixture targets its local disposable server')
const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
assert.equal(manifest.state, 'running')
const ownRoot = resolve(dirname(manifestPath))
const socket = manifest.documents_service_socket
const authority = manifest.documents_authority_socket
const token = manifest.documents_service_token_file
for (const path of [socket, authority, token]) {
  assert.equal(typeof path, 'string', 'Docs path must be generated by --documents')
  assert.ok(resolve(path).startsWith(ownRoot + '/'), 'Docs path belongs to this instance')
  assert.ok(Buffer.byteLength(path) <= 100, 'Use a short private throwaway state path')
}
assert.equal((await stat(token)).mode & 0o777, 0o600)
const output = await mkdtemp(join(tmpdir(), 'crewship-e1-browser-'))
const engineLog = await open(join(output, 'engine.log'), 'w', 0o600)
const engine = spawn(process.execPath, [resolve('tools/docs-service/service.mjs')], {
  env: {CREWSHIP_DOCS_SOCKET:socket, CREWSHIP_DOCS_AUTHORITY_SOCKET:authority, CREWSHIP_DOCS_SERVICE_TOKEN_FILE:token},
  stdio:['ignore',engineLog.fd,engineLog.fd],
})
let browser
try {
  browser = await chromium.launch({headless:true})
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
  const bootstrap = await context.request.post(`${base}/api/v1/bootstrap`, {data:{full_name:'Document Browser',email:'document-browser@example.invalid',password:'disposable-document-browser-password'}})
  assert.equal(bootstrap.status(), 201, 'fresh disposable bootstrap')
  const {workspace_id:workspace} = await bootstrap.json()
  assert.equal(typeof workspace, 'string')
  const complete = await context.request.post(`${base}/api/v1/onboarding/complete`, {data:{skipped:true}})
  assert.equal(complete.status(), 200, 'explicitly skip provider setup')
  let enabled=false
  for(let attempt=0;attempt<100;attempt++) {
    if(engine.exitCode!==null || engine.signalCode!==null) throw new Error('Owned Node engine exited; inspect private engine.log')
    const status = await context.request.get(`${base}/api/v1/documents/status?workspace_id=${encodeURIComponent(workspace)}`)
    enabled=status.ok() && (await status.json()).enabled===true
    if(enabled) break
    await new Promise(resolve=>setTimeout(resolve,100))
  }
  assert.ok(enabled,'real Node service becomes available')
  const page = await context.newPage()
  const errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${base}/pages`)
  await page.getByRole('button',{name:'New Doc',exact:true}).click()
  await page.getByLabel('Name',{exact:true}).fill('Browser notes')
  const initializeReply=page.waitForResponse(response=>response.url().includes('/document/initialize') && response.request().method()==='POST')
  await page.getByRole('button',{name:'Create Doc',exact:true}).click()
  const initialized=await initializeReply
  assert.equal(initialized.status(),200,'initialize through the human UI')
  const initialization=await initialized.json()
  assert.equal(typeof initialization.epoch,'number','initialize uses a durable numeric fence')
  const editor=page.getByLabel('Document editor',{exact:true})
  await editor.waitFor()
  const patchReply=page.waitForResponse(response=>response.url().includes('/document/patch') && response.request().method()==='POST')
  await editor.fill('Browser durable document text')
  const patched=await patchReply
  assert.equal(patched.status(),200,'save through the browser/Node/Go boundary')
  const receipt=await patched.json()
  assert.equal(typeof receipt.epoch,'string','public patch returns opaque epoch')
  await page.getByRole('status').filter({hasText:/^Saved$/}).waitFor()
  const read=await context.request.get(`${base}/api/v1/pages/browser-notes/document?workspace_id=${encodeURIComponent(workspace)}`)
  assert.equal(read.status(),200)
  const saved=await read.json()
  assert.equal(saved.schema,3)
  assert.equal(saved.page_id,initialized.request().postDataJSON().page_id)
  assert.equal(typeof saved.page_id,'string')
  assert.equal(saved.epoch,receipt.epoch)
  assert.ok(saved.rev>=receipt.rev)
  assert.match(JSON.stringify(saved.content),/Browser durable document text/)
  await page.reload()
  await page.getByLabel('Document editor',{exact:true}).waitFor()
  assert.equal(await page.getByLabel('Document editor',{exact:true}).innerText(),'Browser durable document text')
  await page.getByRole('status').filter({hasText:/^Saved$/}).waitFor()
  await page.screenshot({path:join(output,'document-desktop.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),true,'document fits phone viewport')
  await page.screenshot({path:join(output,'document-phone.png'),fullPage:true})
  const touchContext=await browser.newContext({viewport:{width:820,height:1180},hasTouch:true,isMobile:true,reducedMotion:'reduce',storageState:await context.storageState()})
  const touch=await touchContext.newPage()
  touch.on('pageerror',error=>errors.push(error.message))
  await touch.goto(page.url())
  await touch.getByLabel('Document editor',{exact:true}).waitFor()
  assert.equal(await touch.evaluate(()=>matchMedia('(pointer: coarse)').matches),true,'tablet uses a real coarse pointer')
  assert.equal(await touch.evaluate(()=>innerWidth),820,'tablet keeps the desktop-width layout')
  const targets=await touch.locator('[aria-label="Document formatting"] button, [aria-label="Document formatting"] input').evaluateAll(elements=>elements.map(element=>({control:element.getAttribute('aria-label') || element.textContent.trim(),height:element.getBoundingClientRect().height})))
  assert.ok(targets.length>=10,'formatting controls and link input are present')
  const newDoc=touch.getByRole('button',{name:'New Doc',exact:true})
  targets.push({control:'New Doc',height:(await newDoc.boundingBox()).height})
  assert.equal(await newDoc.evaluate(element=>{const box=element.getBoundingClientRect();return [1,box.height-1].every(offset=>document.elementFromPoint(box.x+box.width/2,box.y+offset)?.closest('button')===element)}),true,'the New Doc touch target is not clipped by its header row')
  await touch.screenshot({path:join(output,'document-touch-tablet.png'),fullPage:true})
  await newDoc.tap()
  await touch.getByLabel('Name',{exact:true}).fill('Tablet notes')
  const form=touch.getByRole('dialog').locator('form')
  targets.push(...await form.locator('input, button').evaluateAll(elements=>elements.map(element=>({control:element.id || element.textContent.trim(),height:element.getBoundingClientRect().height}))))
  await touch.screenshot({path:join(output,'document-touch-create.png'),fullPage:true})
  console.log(JSON.stringify({coarseTablet:true,width:820,touchTargets:targets,output}))
  assert.deepEqual(targets.filter(target=>target.height<44),[],'Doc controls have at least 44px touch targets')
  await touch.getByRole('button',{name:'Cancel',exact:true}).tap()
  await touchContext.close()
  assert.deepEqual(errors,[],'no browser runtime errors')
  console.log(JSON.stringify({createdThroughUI:true,schema:3,numericInitialize:true,opaqueReadPatch:true,saveReload:true,phoneFits:true,coarseTabletTargets:true,engine:'production Node',persistence:'Go authority/SQLite',providerInvoked:false,output}))
 } finally {
  try {
    await browser?.close()
  } finally {
    try {
      if(engine.exitCode===null && engine.signalCode===null) {
        const exited=once(engine,'exit')
        engine.kill('SIGTERM')
        let timer
        const finished=await Promise.race([exited.then(()=>true),new Promise(resolve=>{timer=setTimeout(()=>resolve(false),5000)})])
        clearTimeout(timer)
        if(!finished){engine.kill('SIGKILL');await exited}
      }
    } finally { await engineLog.close() }
  }
}
