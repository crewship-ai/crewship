import { expect, test } from "@playwright/test"

test("typed editing, identities, clipped overflow and keyboard Present", async ({ page }, info) => {
  await page.goto("/")
  const snapshot = () => page.getByTestId("deck").textContent().then(value => JSON.parse(value!))
  const original = await snapshot()
  const canvas = page.getByRole("img", { name: "Slide 1", exact: true })
  const frame = await canvas.boundingBox()
  expect(frame!.width / frame!.height).toBeCloseTo(original.width / original.height, 2)
  if (info.project.name === "touch") expect((await page.getByRole("button", { name: "New slide", exact: true }).boundingBox())!.height).toBeGreaterThanOrEqual(44)
  await page.getByRole("button", { name: "Select text 1", exact: true }).click()
  await page.getByRole("textbox", { name: "Text", exact: true }).fill("Hello Czech 🐎 <script>literal text</script>")
  await expect(canvas).toContainText("<script>literal text</script>")
  await page.getByRole("textbox", { name: "Speaker notes", exact: true }).fill("Private notes")
  await page.getByRole("textbox", { name: "Speaker notes", exact: true }).press("ArrowRight")
  await expect(page.getByRole("dialog")).toHaveCount(0)
  await page.screenshot({ path: info.outputPath("editor.png"), fullPage: true })
  await page.getByRole("textbox", { name: "Text", exact: true }).fill("Overflow ".repeat(200))
  await expect(page.getByRole("alert")).toContainText("clipped")
  await page.screenshot({ path: info.outputPath("overflow.png"), fullPage: true })
  await page.getByRole("button", { name: "Duplicate slide", exact: true }).click()
  const duplicated = await snapshot(), originalIds = new Set(original.slides.flatMap((slide: { id: string; elements: { id: string }[] }) => [slide.id, ...slide.elements.map(element => element.id)]))
  const copy = duplicated.slides.find((slide: { id: string }) => !originalIds.has(slide.id))
  expect(copy.elements.every((element: { id: string }) => !originalIds.has(element.id))).toBe(true)
  await page.getByRole("button", { name: "Move slide earlier", exact: true }).click()
  expect((await snapshot()).slide_order[0]).toBe(copy.id)
  const opener = page.getByRole("button", { name: "Present", exact: true })
  await opener.focus(); await opener.press("Enter")
  const dialog = page.getByRole("dialog", { name: "Present slides" })
  await expect(dialog).toBeFocused()
  await page.keyboard.press("ArrowRight")
  await expect(dialog).toContainText("2 / 3")
  await page.keyboard.press("End")
  await expect(dialog).toContainText("3 / 3")
  await page.screenshot({ path: info.outputPath("present.png"), fullPage: true })
  await page.keyboard.press("Escape")
  await expect(dialog).toHaveCount(0); await expect(opener).toBeFocused()
  await page.getByRole("button", { name: "Load unsupported fixture" }).click()
  await expect(page.getByRole("alert")).toContainText("unavailable")
  await expect(page.getByRole("button", { name: "Present", exact: true })).toHaveCount(0)
})
