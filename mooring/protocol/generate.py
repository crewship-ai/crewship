#!/usr/bin/env python3
"""Generate wire shapes, not semantic validators, from the committed partial schema.
No third-party packages or network access. Unsupported schema constructs fail.
"""
import argparse
import json
from pathlib import Path
import re
import subprocess

root = Path(__file__).resolve().parent
schema = json.loads((root / 'schema.json').read_text())
rs = ['// Generated by protocol/generate.py; do not edit.', 'use serde::{Deserialize, Serialize};', 'use crate::Counter;']
go = ['// Code generated by protocol/generate.py; DO NOT EDIT.', '// Wire shapes only: validate schema constraints and cross-field semantics separately.', 'package protocol', 'import "encoding/json"']
ts = ['// Generated by protocol/generate.py; do not edit.', '// Wire shapes only; validate constraints and cross-field semantics separately.']
derive = '#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]'


def title(name):
    return ''.join(p[:1].upper() + p[1:] for p in re.split(r'[_-]', name))


def go_title(name):
    return ''.join(p.upper() if p.lower() in ('id', 'ttl', 'url') else title(p) for p in re.split(r'[_-]', name))


def named(name, node):
    if name == 'Counter':
        go.append('// Counter is a canonical decimal u64 string, never a JSON number.\ntype Counter string')
        ts.append('// Counter is canonical decimal u64 text; use BigInt, never Number.\nexport type Counter = string;')
        return 'Counter', 'Counter', 'Counter'
    if 'oneOf' in node:
        variants = []
        labels = []
        for i, choice in enumerate(node['oneOf']):
            variants.append(typed(name + 'Variant' + str(i + 1), choice))
            label = choice.get('$ref', '').removeprefix('#/$defs/')
            if not label:
                marker = choice.get('properties', {}).get('status', {}).get('const')
                label = title(marker) if isinstance(marker, str) else f'Variant{i+1}'
            if label in labels:
                label = f'Variant{i+1}'
            labels.append(label)
        rs.append(derive + '\n#[serde(untagged)]\npub enum ' + name + ' {\n' + '\n'.join(f'    {label}({v[0]}),' for label, v in zip(labels, variants)) + '\n}')
        # The Go host validates/discriminates the union before interpreting it.
        go.append(f'type {name} = json.RawMessage')
        ts.append(f'export type {name} = ' + ' | '.join(v[2] for v in variants) + ';')
    elif 'enum' in node or 'const' in node:
        values = node.get('enum', [node.get('const')])
        if len(values) == 1 and values[0] is True:
            rs.append(f'pub type {name} = crate::True;')
            go.append(f'type {name} bool')
            ts.append(f'export type {name} = true;')
            return name, name, name
        if not all(isinstance(v, str) for v in values):
            raise ValueError('Only string enums are supported')
        rs.append(derive + '\npub enum ' + name + ' {\n' + '\n'.join('    #[serde(rename = ' + json.dumps(v) + ')]\n    ' + title(v) + ',' for v in values) + '\n}')
        go.append(f'type {name} string\nconst (\n' + '\n'.join(f'    {name}{title(v)} {name} = {json.dumps(v)}' for v in values) + '\n)')
        ts.append(f'export type {name} = ' + ' | '.join(json.dumps(v) for v in values) + ';')
    elif node.get('type') == 'object' and 'properties' in node:
        fields = []
        for key, value in node['properties'].items():
            kind = typed(name + title(key), value)
            fields.append((key, kind, key in node.get('required', [])))
        rust_fields, go_fields, ts_fields = [], [], []
        for key, kind, required in fields:
            rust_key = 'r#type' if key == 'type' else key
            rust_type = kind[0] if required else f'Option<{kind[0]}>'
            attr = '' if required else '    #[serde(default, skip_serializing_if = "Option::is_none")]\n'
            rust_fields.append(f'{attr}    pub {rust_key}: {rust_type},')
            go_type = kind[1] if required else '*' + kind[1]
            tag = key if required else key + ',omitempty'
            go_fields.append(f'    {go_title(key)} {go_type} `json:"{tag}"`')
            ts_fields.append(f'  {key}{"" if required else "?"}: {kind[2]};')
        rs.append(derive + '\n#[serde(deny_unknown_fields)]\npub struct ' + name + ' {\n' + '\n'.join(rust_fields) + '\n}')
        go.append('type ' + name + ' struct {\n' + '\n'.join(go_fields) + '\n}')
        ts.append('export interface ' + name + ' {\n' + '\n'.join(ts_fields) + '\n}')
    else:
        kind = typed(name, node, allow_named=False)
        rs.append(f'pub type {name} = {kind[0]};')
        go.append(f'type {name} {kind[1]}')
        ts.append(f'export type {name} = {kind[2]};')
    return name, name, name


def typed(name, node, allow_named=True):
    if '$ref' in node:
        ref = node['$ref']
        if not ref.startswith('#/$defs/'):
            raise ValueError('External references are unsupported')
        ref = ref.removeprefix('#/$defs/')
        if ref not in schema['$defs']:
            raise ValueError('Unresolved reference')
        return ref, ref, ref
    if allow_named and ('oneOf' in node or 'enum' in node or 'const' in node or 'properties' in node):
        return named(name, node)
    if node.get('type') == 'array':
        item = typed(name + 'Item', node['items'])
        return f'Vec<{item[0]}>', '[]' + item[1], f'Array<{item[2]}>'
    if node.get('type') == 'object':
        return 'serde_json::Map<String, serde_json::Value>', 'map[string]json.RawMessage', 'Record<string, unknown>'
    if node.get('type') == 'boolean':
        return 'bool', 'bool', 'boolean'
    if node.get('type') == 'string':
        return 'String', 'string', 'string'
    raise ValueError(f'Unsupported shape: {node}')


for name, node in schema['$defs'].items():
    named(name, node)
named('Message', {'oneOf': schema['oneOf']})
outputs = {
    root.parent / 'crates/mooring-protocol/src/generated.rs': '\n\n'.join(rs) + '\n',
    root / 'generated/go/types.go': '\n\n'.join(go) + '\n',
    root / 'generated/ts/types.ts': '\n\n'.join(ts) + '\n',
}
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for path, value in outputs.items():
    if path.suffix == ".rs":
        value = subprocess.run(["rustfmt", "--edition", "2021"], input=value, text=True, stdout=subprocess.PIPE, check=True).stdout
    elif path.suffix == ".go":
        value = subprocess.run(["gofmt"], input=value, text=True, stdout=subprocess.PIPE, check=True).stdout
    if args.check:
        if not path.exists() or path.read_text() != value:
            raise SystemExit(f'Generated type drift: {path.relative_to(root.parent)}')
    else:
        path.write_text(value)
print('Rust, Go and TypeScript wire shapes match committed partial schema')
