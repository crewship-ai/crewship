func budgetContext(l RestoreLimits) context.Context {
	return context.WithValue(context.Background(), restoreBudgetKey{}, &restoreBudget{limits: l})
}
func budgetTar(t *testing.T, entries map[string]string, opts ...zstd.EOption) []byte {
	t.Helper()
	var out bytes.Buffer
	w, err := newTarZstWriter(&out, opts...)
	if err != nil {
		t.Fatal(err)
	}
	for name, data := range entries {
		if err := w.WriteFile(name, 0600, time.Now(), []byte(data)); err != nil {
			t.Fatal(err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatal(err)
	}
	return out.Bytes()
}
func TestRestoreBudgetUnknownEntryAutoDrain(t *testing.T) {
	data := budgetTar(t, map[string]string{"ignored": strings.Repeat("x", 4096), "other": "x"})
	limits := DefaultRestoreLimits()
	limits.DecodedBytes = 1024
	reader, err := NewTarZstReader(bytes.NewReader(data), budgetContext(limits))
	if err != nil {
		t.Fatal(err)
	}
	defer reader.Close()
	// The ignored member's body is consumed by tar.Next rather than our caller.
	_, err = reader.Next()
	if err == nil {
		_, err = reader.Next()
	}
	if !errors.Is(err, ErrRestoreLimit) {
		t.Fatalf("ignored contents escaped allowance: %v", err)
	}
}
