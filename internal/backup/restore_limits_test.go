func TestRestoreBudgetWindowLimit(t *testing.T) {
	// A valid zstd frame header advertises a128MiB window, followed by an
	// empty final block. Tiny encoder inputs can silently shrink their window.
	data := []byte{0x28, 0xb5, 0x2f, 0xfd, 0x00, 0x88, 0x01, 0x00, 0x00}
	var header zstd.Header
	if err := header.Decode(data); err != nil || header.WindowSize != 128<<20 {
		t.Fatalf("window fixture: %+v %v", header, err)
	}
	limits := DefaultRestoreLimits()
	limits.DecoderWindow = 1 << 20
	limits.DecoderMemory = 1 << 20
	r, err := NewTarZstReader(bytes.NewReader(data), budgetContext(limits))
	if err == nil {
		_, err = r.Next()
		_ = r.Close()
	}
	if !resourceFailure(err) {
		t.Fatalf("oversized window not rejected: %v", err)
	}
}
