func TestRestoreBudgetReleaseIsIdempotent(t *testing.T) {
	_, release, err := BeginRestoreRead(context.Background())
	if err != nil {
		t.Fatal(err)
	}
	restoreAdmission.Lock()
	active := restoreAdmission.active
	restoreAdmission.Unlock()
	release()
	release()
	restoreAdmission.Lock()
	defer restoreAdmission.Unlock()
	if restoreAdmission.active != active-1 {
		t.Fatalf("double cleanup changed admission twice: %d", restoreAdmission.active)
	}
}

