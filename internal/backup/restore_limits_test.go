func TestRestoreBudgetOpaqueVerifyCompatibility(t *testing.T) {
	var out bytes.Buffer
	if err := WriteBundle(&out, newValidManifest(), strings.NewReader("legacy opaque payload"), WriteBundleOptions{NoEncrypt: true}); err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(t.TempDir(), "opaque.tar.zst")
	if err := os.WriteFile(path, out.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	result, err := Verify(t.Context(), path)
	if err != nil || !result.Valid {
		t.Fatalf("legacy verify: %+v %v", result, err)
	}
	// Corrupting the recorded checksum remains a full Verify failure.
	var stream bytes.Buffer
	m := newValidManifest()
	m.Checksums.PayloadSHA256 = "sha256:" + strings.Repeat("0", 64)
	if err := WriteBundleStream(&stream, m, strings.NewReader("opaque"), 6); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, stream.Bytes(), 0600); err != nil {
		t.Fatal(err)
	}
	result, err = Verify(t.Context(), path)
	if err != nil || result.Valid {
		t.Fatalf("corrupt verify accepted: %+v %v", result, err)
	}
}
